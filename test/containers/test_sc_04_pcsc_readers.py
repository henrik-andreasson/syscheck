"""End-to-end tests for scripts-available/sc_04_pcsc_readers.sh.

The reader count comes from `lib/list-pcsc-readers.py`, which needs pyscard and
real PC/SC hardware, so the tests replace that one file — the fixtures are the
exact strings that script prints, read off it rather than invented:

    print("Found number of readers:{}".format(len(r)))
    print("Can not find any attached readers")
    print("Can not establish contact with PCSC")

The fourth case, pyscard not installed, needs no fake at all: the image has
python3 and no pyscard, so running the real `lib/list-pcsc-readers.py`
reproduces the genuine `ModuleNotFoundError` traceback the script greps for.
The harness restores `lib/` between tests, so replacing the file is safe.
"""

from __future__ import annotations

import pytest

SCRIPT = "sc_04_pcsc_readers.sh"
LISTER = "lib/list-pcsc-readers.py"

READER_NAMES = [
    "Gemalto PC Twin Reader 00 00",
    "OMNIKEY AG CardMan 3121 01 00",
]


def config(expected: int = 1) -> str:
    return (
        "# generated by test_sc_04_pcsc_readers.py\n"
        f"PCSC_NUMBER_OF_READERS={expected}\n"
    )


@pytest.fixture
def readers(syscheck):
    """sc_04 with `lib/list-pcsc-readers.py` under the test's control."""

    def found(count: int) -> None:
        lines = [f"Found number of readers:{count}"] + READER_NAMES[:count]
        set_output("\n".join(lines) + "\n")

    def set_output(text: str) -> None:
        syscheck.write_file(f"{syscheck.home}/{LISTER}",
                            "#!/bin/bash\ncat <<'EOT'\n" + text + "EOT\n",
                            mode=0o755)

    syscheck.found = found
    syscheck.set_output = set_output
    syscheck.set_script_config("04", config())
    return syscheck


def test_the_expected_number_of_readers_is_reported_ok(readers):
    readers.found(1)

    run = readers.run_script(SCRIPT)

    msg = run.only()
    assert (msg.level, msg.errno, msg.index) == ("I", "041", "01"), run.describe()
    assert "(1)" in msg.text, msg.text


def test_more_readers_than_expected_is_an_error(readers):
    readers.set_script_config("04", config(expected=1))
    readers.found(2)

    run = readers.run_script(SCRIPT)

    msg = run.only()
    assert (msg.level, msg.errno) == ("E", "042"), run.describe()
    assert "(2)" in msg.text and "(1)" in msg.text, msg.text


def test_fewer_readers_than_expected_is_an_error(readers):
    """The failure this check exists for: a reader was unplugged, or its USB
    port stopped answering."""
    readers.set_script_config("04", config(expected=2))
    readers.found(1)

    run = readers.run_script(SCRIPT)

    msg = run.only()
    assert (msg.level, msg.errno) == ("E", "042"), run.describe()


def test_the_reader_names_do_not_affect_the_count(readers):
    """Only the first line is parsed, and the names that follow it contain
    digits and colons of their own."""
    readers.set_script_config("04", config(expected=2))
    readers.found(2)

    run = readers.run_script(SCRIPT)

    assert run.only().errno == "041", run.describe()


def test_no_attached_readers_is_an_error(readers):
    """`readers()` returned an empty list, so the count line is never printed."""
    readers.set_output("Can not find any attached readers\n")

    run = readers.run_script(SCRIPT)

    assert run.only().level == "E", run.describe()


def test_a_dead_pcscd_is_an_error(readers):
    """`EstablishContextException` — the daemon sc_05 checks is not answering,
    so no count can be read at all."""
    readers.set_output("Can not establish contact with PCSC\n")

    run = readers.run_script(SCRIPT)

    assert run.only().level == "E", run.describe()


def test_a_missing_pyscard_module_is_reported_as_a_warning(readers):
    """No fake: the real `lib/list-pcsc-readers.py` on an image without pyscard
    produces the genuine traceback, which is what the script greps for."""
    run = readers.run_script(SCRIPT)

    msg = run.only()
    assert (msg.level, msg.errno) == ("W", "043"), run.describe()
    assert "smartcard" in msg.text, msg.text


def test_exactly_one_message_is_emitted_per_run(readers):
    readers.found(1)

    run = readers.run_script(SCRIPT)

    assert len(run.messages) == 1, run.describe()


def test_help_documents_every_error_code(readers):
    res = readers.exec([readers.script_path(SCRIPT), "--help"])

    for errno in ("041", "042", "043"):
        assert f"{errno} / " in res.output, res.output


def test_the_module_missing_message_carries_a_real_index(readers):
    """The regression guard for D29. `initscript` leaves `SCRIPTINDEX=00`, and
    sc_04 used to call `addOneToIndex` only *after* the pyscard check, so this
    message went out under index 00 — an index no other message in this script
    ever uses, and therefore a monitoring service name that only ever appears
    when the module is missing. The two messages are exclusive outcomes of one
    check, so they share index 01."""
    run = readers.run_script(SCRIPT)

    assert run.only().index == "01", run.describe()

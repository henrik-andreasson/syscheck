"""End-to-end tests for related-available/920_restore_mysql_db_from_backup.sh.

`920` restores a gzipped dump over the live database. Before doing so it asks
for interactive confirmation and takes a safety backup by calling `904`.

REAL-SVC: a real `mariadb:11`. The dumps restored here are produced by the real
`904`, so this suite and `test_904_make_mysql_db_backup.py` together prove a
genuine round trip — data goes out through `mysqldump` and comes back through
`920`, and the rows are checked on the far side.

`920` reads its confirmation from stdin, so every invocation here is driven
through `exec` with the answer piped in rather than through `run_script`.
"""

from __future__ import annotations

import pytest

from conftest import MARIADB_DATABASE, MARIADB_ROOT_PASSWORD
from syscheck_harness import parse_messages

SCRIPT = "related-available/920_restore_mysql_db_from_backup.sh"
BACKUP_SCRIPT = "related-available/904_make_mysql_db_backup.sh"
BACKUPDIR = "/tmp/920/backup"
TABLE = "CertificateData"
CONFIRM = "im really sure"

pytestmark = pytest.mark.slow


def mariadb_config(password: str = MARIADB_ROOT_PASSWORD) -> str:
    return ("# generated by test_920_restore_mysql_db_from_backup.py\n"
            f"DB_NAME={MARIADB_DATABASE}\n"
            f'MYSQLROOT_PASSWORD="{password}"\n'
            "MYSQL_BIN=/usr/bin/mariadb\n"
            "MYSQLDUMP_BIN=/usr/bin/mariadb-dump\n"
            "MYSQLDUMP_OPTIONS=(--single-transaction --quick)\n")


def backup_config() -> str:
    return ("# generated by test_920_restore_mysql_db_from_backup.py\n"
            "DATESTING='%Y-%m-%d_%H.%M.%S'\n"
            f"MYSQLBACKUPDIR={BACKUPDIR}\n"
            "SUBDIR_DEFAULT=default\n"
            "SUBDIR_DAILY=daily\nSUBDIR_WEEKLY=weekly\n"
            "SUBDIR_MONTHLY=monthly\nSUBDIR_YEARLY=yearly\n"
            f'DBNAME[0]="{MARIADB_DATABASE}"\n'
            'TABLENAMES[0]=""\n')


@pytest.fixture
def restore(syscheck, mariadb_node):
    syscheck.write_file("/root/.my.cnf", f"[client]\nhost={mariadb_node}\n")
    syscheck.exec(f"rm -rf /tmp/920 && mkdir -p {BACKUPDIR}/default").check()

    def sql(statement: str) -> str:
        res = syscheck.exec(["mariadb", "-h", mariadb_node, "-uroot",
                             f"-p{MARIADB_ROOT_PASSWORD}", MARIADB_DATABASE,
                             "-N", "-e", statement])
        assert res.exit_code == 0, res.output
        return res.stdout

    def rows() -> list[str]:
        return sorted(r for r in sql(f"select fingerprint from {TABLE}").split())

    sql(f"DROP TABLE IF EXISTS {TABLE}")
    sql(f"CREATE TABLE {TABLE} (fingerprint VARCHAR(64) PRIMARY KEY)")
    sql(f"INSERT INTO {TABLE} VALUES ('aa'),('bb')")

    syscheck.set_script_config("mariadb", mariadb_config())
    syscheck.set_script_config("904", backup_config())
    syscheck.sql = sql
    syscheck.rows = rows
    return syscheck


def make_backup(sc) -> str:
    """A real dump taken by the real `904`, which is what `920` restores.

    The trailing `sleep 1` is load-bearing. `904` names its file from
    `%Y-%m-%d_%H.%M.%S`, and `920` takes a safety backup of the same database
    moments later; within the same second the two names collide and D98
    destroys this file before it can be restored. One second apart is enough to
    keep these tests about `920` rather than about D98, which
    `test_904_make_mysql_db_backup.py` pins directly.
    """
    res = sc.exec([sc.script_path(BACKUP_SCRIPT), "--batch"]).check()
    name = [l.strip() for l in res.stdout.splitlines() if l.strip().endswith(".gz")]
    assert len(name) == 1, res.output
    sc.exec("sleep 1")
    return name[0]


def run(sc, *args, answer: str = CONFIRM, seconds: int = 60):
    argv = " ".join(args)
    res = sc.exec(f"printf '%s\\n' '{answer}' | "
                  f"timeout {seconds} {sc.script_path(SCRIPT)} --screen {argv}")
    messages, _j, _u = parse_messages(res.stdout + res.stderr)
    return res, [m for m in messages if m.scriptid == "920"]


# --- the round trip ---------------------------------------------------------

def test_a_backup_taken_by_904_restores_the_rows_it_held(restore):
    """The point of the pair. Dump two rows, destroy them, restore, get them
    back — through the real `mysqldump` and the real client."""
    dump = make_backup(restore)
    restore.sql(f"DELETE FROM {TABLE}")
    assert restore.rows() == []

    run(restore, f"--backupfile={dump}")

    assert restore.rows() == ["aa", "bb"]


def test_a_successful_restore_is_reported(restore):
    dump = make_backup(restore)

    _res, messages = run(restore, f"--backupfile={dump}")

    assert any(m.errno == "9202" for m in messages), messages


def test_rows_added_after_the_backup_are_rolled_back(restore):
    """Restoring is destructive by design — the dump replaces what is there.
    Proving it removes newer rows is proving the restore actually took."""
    dump = make_backup(restore)
    restore.sql(f"INSERT INTO {TABLE} VALUES ('cc')")
    assert restore.rows() == ["aa", "bb", "cc"]

    run(restore, f"--backupfile={dump}")

    assert restore.rows() == ["aa", "bb"]


# --- the safety backup ------------------------------------------------------

def test_a_safety_backup_is_taken_before_restoring(restore):
    """`920` calls `904` first, so the state being overwritten is recoverable.
    Two files in the backup directory afterwards: the one being restored and
    the one just taken."""
    dump = make_backup(restore)
    before = restore.exec(f"ls -1 {BACKUPDIR}/default | wc -l").check().stdout.strip()

    run(restore, f"--backupfile={dump}")

    after = restore.exec(f"ls -1 {BACKUPDIR}/default | wc -l").check().stdout.strip()
    assert int(after) == int(before) + 1, f"{before} -> {after}"


def test_a_failing_safety_backup_aborts_the_restore(restore):
    """If the pre-restore backup cannot be taken, the restore must not proceed —
    there would be no way back."""
    dump = make_backup(restore)
    restore.set_script_config("904", backup_config().replace(
        f"MYSQLBACKUPDIR={BACKUPDIR}", "MYSQLBACKUPDIR=/tmp/920/gone"))
    restore.sql(f"DELETE FROM {TABLE}")

    _res, messages = run(restore, f"--backupfile={dump}")

    assert any(m.errno == "9201" for m in messages), messages
    assert restore.rows() == [], "the restore ran despite the safety backup failing"


# --- the confirmation -------------------------------------------------------

def test_the_wrong_answer_aborts_without_touching_the_database(restore):
    dump = make_backup(restore)
    restore.sql(f"DELETE FROM {TABLE}")

    run(restore, f"--backupfile={dump}", answer="no")

    assert restore.rows() == [], "the database was restored despite declining"


def test_an_empty_answer_aborts(restore):
    dump = make_backup(restore)
    restore.sql(f"DELETE FROM {TABLE}")

    run(restore, f"--backupfile={dump}", answer="")

    assert restore.rows() == []



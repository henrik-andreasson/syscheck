"""End-to-end tests for related-available/932_send_result_as_message.sh.

`932` is the other outbound path: it hands `var/last_status` to a configured
message command — in the shipped config a vendor tool,
`send-vcom-message.sh` — invoked as `<command> -c <config> -m <file>`.

FAKE-BIN: the vendor tool is not in this tree, so a stub stands in. It records
its argv and can be made to succeed or fail, which is the whole seam: `932` adds
a loop and a report and nothing else.

Where `929`/`930` filter and ship a file, `932` is the path that tells a human
the system is unhealthy. That makes its one real defect — a failed send being
reported as a success — the most consequential kind for a script of this size.
"""

from __future__ import annotations

import pytest

SCRIPT = "related-available/932_send_result_as_message.sh"
WORK = "/tmp/932"
CALL_LOG = f"{WORK}/calls.log"
STATUS = "/opt/syscheck/var/last_status"
MSG_CONFIG = f"{WORK}/vcom.properties"

pytestmark = pytest.mark.slow


def config(*, entries: int = 1, command: str = "/usr/local/bin/send-msg",
           status: str = STATUS) -> str:
    lines = ["# generated by test_932_send_result_as_message.py\n"]
    for i in range(entries):
        lines.append(f'SEND_MSG_COMMAND[{i}]="{command}"\n')
        lines.append(f'SEND_MSG_CONFIG[{i}]="{MSG_CONFIG}"\n')
        lines.append(f'SEND_MSG_FILE[{i}]="{status}"\n')
    return "".join(lines)


def install_sender(sc, *, rc: int = 0, out: str = "message accepted") -> None:
    sc.install_fake_bin("send-msg",
                        "#!/bin/bash\n"
                        f'echo "$@" >> {CALL_LOG}\n'
                        f"echo '{out}'\n"
                        f"exit {rc}\n")


@pytest.fixture
def sender(syscheck):
    syscheck.exec(f"rm -rf {WORK} && mkdir -p {WORK} && "
                  f"echo 'vcom.host=example' > {MSG_CONFIG}").check()
    syscheck.write_file(STATUS, "01-01-I-011-PKI 20260917 06:00:00 host: INFO - ok\n")
    install_sender(syscheck)
    syscheck.set_script_config("932", config())
    return syscheck


def own(run) -> list:
    return [m for m in run.messages if m.scriptid == "932"]


def calls(sc) -> list[str]:
    if not sc.file_exists(CALL_LOG):
        return []
    return [l for l in sc.read_file(CALL_LOG).splitlines() if l.strip()]


# --- the invocation ---------------------------------------------------------

def test_the_message_command_is_invoked(sender):
    sender.run_script(SCRIPT)

    assert calls(sender), "the message command was never called"


def test_the_configured_config_and_file_are_passed(sender):
    """`-c <config> -m <file>` is the vendor tool's interface; getting either
    wrong means the message goes nowhere or carries the wrong content."""
    sender.run_script(SCRIPT)

    assert f"-c {MSG_CONFIG}" in calls(sender)[0], calls(sender)
    assert f"-m {STATUS}" in calls(sender)[0], calls(sender)


def test_a_successful_send_is_reported(sender):
    run = sender.run_script(SCRIPT)

    msg = own(run)[0]
    assert (msg.level, msg.errno) == ("I", "9321"), run.describe()


def test_the_message_names_the_command_and_its_output(sender):
    """`DESCR[1]` carries both, which is how an operator confirms *which*
    destination accepted the message."""
    run = sender.run_script(SCRIPT)

    assert "send-msg" in own(run)[0].text, own(run)[0].text
    assert "accepted" in own(run)[0].text, own(run)[0].text


def test_the_tool_output_is_flattened_to_one_line(sender):
    """`tr -d '\\n'` keeps a chatty vendor tool from breaking the log format."""
    install_sender(sender, out="line one\nline two")

    run = sender.run_script(SCRIPT)

    assert len(own(run)) == 1, run.describe()
    assert "line oneline two" in own(run)[0].text, own(run)[0].text


# --- several destinations ---------------------------------------------------

def test_every_configured_destination_is_sent_to(sender):
    sender.set_script_config("932", config(entries=2))

    run = sender.run_script(SCRIPT)

    assert len(calls(sender)) == 2, calls(sender)
    assert len(own(run)) == 2, run.describe()


def test_each_destination_reports_under_its_own_index(sender):
    sender.set_script_config("932", config(entries=2))

    run = sender.run_script(SCRIPT)

    indexes = [m.index for m in own(run)]
    assert len(set(indexes)) == len(indexes), run.describe()


def test_no_configured_destinations_does_nothing(sender):
    sender.set_script_config("932", config(entries=0))

    run = sender.run_script(SCRIPT)

    assert calls(sender) == []
    assert own(run) == [], run.describe()


# --- known defect -----------------------------------------------------------

def test_a_failing_send_is_reported_as_an_error(sender):
    """D140, fixed 2026-09-17. `932` captures the tool's output through a pipe:

        SENDRES=$(${SEND_MSG_COMMAND[$j]} -c ... -m ... | tr -d '\\n')
        if [ $? -ne 0 ] ; then

    `$?` after a pipeline is the exit status of its **last** command, which is
    `tr` — and `tr` always succeeds. Measured: `false | tr -d "\\n"` gives 0.
    So the failure branch is unreachable and `932` reports `ERRNO[1]`,
    "Transfer ok", no matter what the vendor tool did.

    This is the same masking as D125 in `900`/`901`, and materially worse.
    There, a later un-piped call caught the same condition, so no failure was
    *missed* — only misattributed. Here there is no second check: the failure is
    simply lost.

    And it is lost in the one place it cannot be afforded. `932` exists to tell
    a human the system is unhealthy; a broken notification path that reports
    itself as healthy is indistinguishable from a healthy system, which is
    exactly the state an operator is trusting this script to rule out.

    `904` uses `pipefail` for the same shape of problem."""
    install_sender(sender, rc=1, out="connection refused")

    run = sender.run_script(SCRIPT)

    msg = own(run)[0]
    assert (msg.level, msg.errno) == ("E", "9322"), run.describe()


def test_a_failing_send_still_records_the_tool_output(sender):
    """The tool's own words reach the message, so an operator sees why the send
    failed and not merely that it did."""
    install_sender(sender, rc=1, out="connection refused")

    run = sender.run_script(SCRIPT)

    assert "connection refused" in own(run)[0].text, own(run)[0].text


def test_help_documents_every_error_code(sender):
    res = sender.exec([sender.script_path(SCRIPT), "--help"])

    for errno in ("9321", "9322"):
        assert f"{errno} / " in res.output, res.output

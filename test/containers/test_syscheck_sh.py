def test_last_status_starts_with_the_date_of_the_run(orchestrator):
    orchestrator.enable(ALIVE)

    orchestrator.run_syscheck()

    first_line = orchestrator.last_status().splitlines()[0]
    assert orchestrator.exec(f"date -d {first_line!r} +%s").exit_code == 0, first_line


def test_last_status_holds_one_line_per_enabled_check(orchestrator):
    orchestrator.enable(ALIVE)
    orchestrator.enable(APACHE)

    orchestrator.run_syscheck()

    lines = orchestrator.last_status().splitlines()
    assert len(lines) == 3, lines          # the date, then one line per check
    assert "apache" in lines[1], lines
    assert "alive" in lines[2], lines


def test_last_status_is_replaced_by_each_run(orchestrator):
    """It is the *last* status, not a log: `929_filter_syscheck_messages.sh` and
    the monitoring hand-off both read it as the current state of the host, so a
    previous run's findings must not survive into it."""
    orchestrator.enable(ALIVE)
    orchestrator.write_file(f"{orchestrator.home}/var/last_status",
                            "STALE LINE FROM AN EARLIER RUN\n")

    orchestrator.run_syscheck()

    status = orchestrator.last_status()
    assert "STALE" not in status, status
    assert len(status.splitlines()) == 2, status


def test_last_status_is_written_in_oldfmt(orchestrator):
    """`SAVELASTSTATUS_OUTPUTTYPE` defaults to OLDFMT, which is what 929 parses.
    Pinned because the default lives in `syscheck-scripts.conf` while the
    parser lives in another script entirely."""
    orchestrator.enable(ALIVE)

    orchestrator.run_syscheck()

    line = orchestrator.last_status().splitlines()[1]
    assert line.startswith("I-19193-"), line



def test_testall_runs_checks_that_are_not_enabled(orchestrator):
    """The point of the flag: try everything in the catalogue, whatever the
    site has turned on."""
    orchestrator.trim_catalogue()
    orchestrator.marker("sc_82_not_enabled.sh", available_only=True)

    orchestrator.run_syscheck("--testall")

    assert "sc_82_not_enabled.sh" in orchestrator.ran()


def test_testall_does_not_run_the_after_run_hooks(orchestrator):
    """A by-hand diagnostic run must not ship its results to the remote machine
    or page anyone."""
    orchestrator.set_script_config("00", config(
        FILTER_SYSCHECK_AFTER_RUN=1,
        SEND_SYSCHECK_RESULT_TO_REMOTE_MACHINE_AFTER_FILTER=1,
        SEND_SYSCHECK_RESULT_AS_MESSAGE=1,
    ))
    for which in HOOKS:
        orchestrator.stub_hook(which)
    orchestrator.trim_catalogue()
    orchestrator.marker("sc_82_not_enabled.sh", available_only=True)

    orchestrator.run_syscheck("--testall")

    assert [name for name in orchestrator.ran() if name.startswith("hook-")] == []



"""Tests for syscheck.sh, the orchestrator every check runs under.

`syscheck.sh` is what cron invokes. It parses the operator's flags, decides
which checks run, resets `var/last_status`, and afterwards calls up to three
`related-enabled` hooks. Until now exactly one test touched it — the getopt
regression in `test_shared_library.py` — so the 294 tests in this suite all ran
*under* code that nothing verified.

Two kinds of stand-in are used, and the difference matters:

* **marker scripts** — executables dropped into `scripts-enabled` that record
  that they ran. `syscheck.sh` executes whatever it finds there without caring
  what it is, so these answer "which scripts ran, in what order" exactly.
* **real checks** — `sc_19_alive.sh` (one INFO, no config needed) and
  `sc_15_apache.sh` (one ERROR on this container, since no apache is running)
  for the questions that need genuine syscheck messages, such as what reaches
  `last_status` and in which format.

The hooks are stubbed rather than run: `930_send_filtered_result_to_remote_machine.sh`
copies to a remote host over ssh, and the question here is whether
`syscheck.sh` calls it, not what it does.
"""

from __future__ import annotations

import pytest

SYSCHECK = "syscheck.sh"
RAN_LOG = "/tmp/syscheck-ran.log"
HOLD_FILE_NAME = "var/syscheck-on-hold"

ALIVE = "sc_19_alive.sh"
APACHE = "sc_15_apache.sh"

HOOKS = {
    "filter": "929_filter_syscheck_messages.sh",
    "send": "930_send_filtered_result_to_remote_machine.sh",
    "message": "932_send_result_as_message.sh",
}


def config(**flags) -> str:
    """config/00.conf — empty as shipped, and sourced after common.conf, so it
    is where the after-run hook flags get switched on for a test."""
    lines = ["# generated by test_syscheck_sh.py\n"]
    lines += [f"{name}={value}\n" for name, value in flags.items()]
    return "".join(lines)


@pytest.fixture
def orchestrator(syscheck):
    """A syscheck install with nothing enabled and a clean run log."""
    syscheck.exec(f"rm -f {RAN_LOG}")

    def marker(name: str, available_only: bool = False) -> None:
        """An executable that records that it ran. Lands in scripts-available,
        and in scripts-enabled too unless the test wants it left out."""
        body = f'#!/bin/bash\necho {name} >>{RAN_LOG}\n'
        syscheck.write_file(f"{syscheck.home}/scripts-available/{name}", body, mode=0o755)
        if not available_only:
            syscheck.exec(
                f"ln -sf {syscheck.home}/scripts-available/{name} "
                f"{syscheck.home}/scripts-enabled/{name}"
            ).check()

    def enable(script: str) -> None:
        """Enable one of the real checks."""
        syscheck.exec(
            f"ln -sf {syscheck.home}/scripts-available/{script} "
            f"{syscheck.home}/scripts-enabled/{script}"
        ).check()

    def stub_hook(which: str) -> None:
        body = f'#!/bin/bash\necho hook-{which} >>{RAN_LOG}\n'
        syscheck.write_file(f"{syscheck.home}/related-enabled/{HOOKS[which]}",
                            body, mode=0o755)

    def trim_catalogue(*keep: str) -> None:
        """Empty scripts-available except for `keep`.

        Only for the `--testall` tests: that flag runs the entire catalogue, and
        several real checks block on a network timeout or a 5s sleep, which made
        four tests cost ten minutes between them. What is under test is which
        directory `--testall` reads, not whether all 38 checks work — they have
        their own suites. The harness restores the tree between tests."""
        kept = " ".join(f"! -name {name}" for name in keep)
        syscheck.exec(
            f"find {syscheck.home}/scripts-available -name 'sc_*' {kept} -delete"
        ).check()

    def ran() -> list[str]:
        if not syscheck.file_exists(RAN_LOG):
            return []
        return syscheck.read_file(RAN_LOG).split()

    def run(*args: str):
        return syscheck.run_script(SYSCHECK, *args, screen=False)

    syscheck.marker = marker
    syscheck.enable = enable
    syscheck.trim_catalogue = trim_catalogue
    syscheck.stub_hook = stub_hook
    syscheck.ran = ran
    syscheck.run_syscheck = run
    return syscheck



def test_only_the_scripts_in_scripts_enabled_are_run(orchestrator):
    """`scripts-available` is the catalogue, `scripts-enabled` is the selection.
    A check present but not enabled must stay silent — that is the entire
    mechanism by which a site turns a check off."""
    orchestrator.marker("sc_81_enabled.sh")
    orchestrator.marker("sc_82_not_enabled.sh", available_only=True)

    orchestrator.run_syscheck()

    assert orchestrator.ran() == ["sc_81_enabled.sh"]


def test_the_enabled_scripts_run_in_script_id_order(orchestrator):
    """The glob sorts by filename, which begins with the script id, so the run
    order is by id regardless of what the rest of the name is or of the order
    they were enabled in."""
    orchestrator.marker("sc_44_zulu.sh")
    orchestrator.marker("sc_03_yankee.sh")
    orchestrator.marker("sc_19_alpha.sh")

    orchestrator.run_syscheck()

    assert orchestrator.ran() == ["sc_03_yankee.sh", "sc_19_alpha.sh", "sc_44_zulu.sh"]


def test_a_real_check_reports_through_the_orchestrator(orchestrator):
    orchestrator.enable(ALIVE)

    run = orchestrator.run_syscheck("--screen")

    msg = run.only()
    assert (msg.level, msg.errno, msg.scriptname) == ("I", "193", "alive"), run.describe()


def test_every_enabled_check_reports_once(orchestrator):
    """Two checks, two messages: the loop must not stop at the first, and must
    not run anything twice."""
    orchestrator.enable(ALIVE)
    orchestrator.enable(APACHE)

    run = orchestrator.run_syscheck("--screen")

    assert [m.scriptid for m in run.messages] == ["15", "19"], run.describe()



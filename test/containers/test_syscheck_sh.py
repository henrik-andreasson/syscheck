def test_a_held_syscheck_runs_nothing(orchestrator):
    """`initscript` calls `isSyscheckOnHold` for scriptid 00 as well, so the
    hold file stops the orchestrator itself, not just the individual checks."""
    orchestrator.marker("sc_81_marker.sh")
    orchestrator.exec(
        f'printf "$(date);maintenance;alice" > {orchestrator.home}/{HOLD_FILE_NAME}'
    ).check()

    orchestrator.run_syscheck("--screen")

    assert orchestrator.ran() == []


def test_a_held_run_prints_the_bare_00_to_the_operator(orchestrator):
    """Pins the behaviour D8 recorded as intentional: `isSyscheckOnHold` runs
    inside `initscript`, before `--screen` has been parsed, so `PRINTTOSCREEN`
    is still 0 and the notice cannot be routed to the terminal. What an
    operator running `syscheck.sh --screen` on a held host actually sees is the
    literal `00` from the bare `printf`. The notice itself reaches the log."""
    orchestrator.exec(
        f'printf "$(date);maintenance;alice" > {orchestrator.home}/{HOLD_FILE_NAME}'
    ).check()

    run = orchestrator.run_syscheck("--screen")

    assert run.output.strip() == "00", run.describe()
    assert "SYSCHECK IS ON HOLD BY: alice" in orchestrator.file_log(), orchestrator.file_log()



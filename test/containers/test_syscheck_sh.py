@pytest.mark.parametrize("flag", ["--screen", "-s"])
def test_the_screen_flag_reaches_the_checks(orchestrator, flag):
    """`PRINTTOSCREEN` is exported by `syscheck.sh` and read by every child
    script, so this flag is the only thing standing between an operator running
    syscheck by hand and a completely silent terminal."""
    orchestrator.enable(ALIVE)

    run = orchestrator.run_syscheck(flag)

    assert len(run.messages) == 1, run.describe()


def test_without_the_screen_flag_the_run_is_silent_but_still_logged(orchestrator):
    """Cron mode: nothing on the terminal, everything in the log file."""
    orchestrator.enable(ALIVE)

    run = orchestrator.run_syscheck()

    assert run.messages == [], run.describe()
    assert "alive" in orchestrator.file_log(), orchestrator.file_log()


def test_help_exits_without_running_any_check(orchestrator):
    orchestrator.marker("sc_81_marker.sh")

    res = orchestrator.exec([f"{orchestrator.home}/{SYSCHECK}", "--help"])

    assert res.exit_code == 0, res.output
    assert "Syscheck master script" in res.output, res.output
    assert orchestrator.ran() == []


def test_an_unknown_option_runs_no_checks(orchestrator):
    """Refusing the whole run is the right call — a mistyped flag must not turn
    into a partial run that looks like a complete one."""
    orchestrator.marker("sc_81_marker.sh")

    res = orchestrator.exec([f"{orchestrator.home}/{SYSCHECK}", "--nonsense"])

    assert res.exit_code != 0, res.output
    assert orchestrator.ran() == []



@pytest.mark.parametrize("flag, which", [
    ("FILTER_SYSCHECK_AFTER_RUN", "filter"),
    ("SEND_SYSCHECK_RESULT_TO_REMOTE_MACHINE_AFTER_FILTER", "send"),
    ("SEND_SYSCHECK_RESULT_AS_MESSAGE", "message"),
])
def test_each_hook_runs_when_its_flag_is_set(orchestrator, flag, which):
    orchestrator.enable(ALIVE)
    for hook in HOOKS:
        orchestrator.stub_hook(hook)
    orchestrator.set_script_config("00", config(**{flag: 1}))

    orchestrator.run_syscheck()

    assert orchestrator.ran() == [f"hook-{which}"]


def test_the_hooks_run_in_order_after_the_checks(orchestrator):
    """Filter first, then the transfer of the filtered result, then the
    message: 930 sends what 929 produced, so the order is the contract."""
    orchestrator.marker("sc_81_check.sh")
    for which in HOOKS:
        orchestrator.stub_hook(which)
    orchestrator.set_script_config("00", config(
        FILTER_SYSCHECK_AFTER_RUN=1,
        SEND_SYSCHECK_RESULT_TO_REMOTE_MACHINE_AFTER_FILTER=1,
        SEND_SYSCHECK_RESULT_AS_MESSAGE=1,
    ))

    orchestrator.run_syscheck()

    assert orchestrator.ran() == [
        "sc_81_check.sh", "hook-filter", "hook-send", "hook-message",
    ]



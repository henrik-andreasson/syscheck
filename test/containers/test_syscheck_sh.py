def test_an_empty_scripts_enabled_directory_runs_nothing_and_exits_zero(orchestrator):
    """A fresh install: nothing is enabled, the glob matches nothing, bash
    passes the pattern through literally and `$file` is executed as a filename
    containing `*`. The shell error goes to stderr; the exit status is 0."""
    res = orchestrator.exec([f"{orchestrator.home}/{SYSCHECK}"])

    assert res.exit_code == 0, res.output
    assert "scripts-enabled/sc_*: No such file or directory" in res.output, res.output


def test_an_enabled_hook_that_is_not_installed_exits_zero(orchestrator):
    """`related-enabled` is empty as shipped, so turning on
    `FILTER_SYSCHECK_AFTER_RUN` in `common.conf` without also linking 929 is the
    ordinary way to reach this. Same shape as above: a shell error, exit 0."""
    orchestrator.enable(ALIVE)
    orchestrator.set_script_config("00", config(FILTER_SYSCHECK_AFTER_RUN=1))

    res = orchestrator.exec([f"{orchestrator.home}/{SYSCHECK}"])

    assert res.exit_code == 0, res.output
    assert "929_filter_syscheck_messages.sh: No such file or directory" in res.output


def test_testall_does_not_corrupt_the_last_status_of_the_real_run(orchestrator):
    """The regression guard for D34. `--testall` returns before the `rm -f`/
    `date >` that starts a normal run, but the checks it ran still appended to
    `last_status` through `SAVELASTSTATUS`. So a by-hand `--testall` left the
    file holding the last cron run's date header followed by a mixture of both
    runs — including results from checks this host has deliberately not enabled
    — and whatever read `last_status` next, 929 or the remote transfer, took
    that mixture for the current state of the host."""
    orchestrator.trim_catalogue(ALIVE)
    orchestrator.enable(ALIVE)
    orchestrator.run_syscheck()
    before = orchestrator.last_status()

    orchestrator.marker("sc_82_not_enabled.sh", available_only=True)
    orchestrator.run_syscheck("--testall")

    assert orchestrator.last_status() == before, orchestrator.last_status()[:400]

"""End-to-end tests for related-available/906_ssh-copy-to-remote-machine.sh.

`906` copies one file to a remote host over sftp and verifies it arrived
intact. Before sending it asks the remote — through `915` — whether the file is
already there and whether there is room for it; afterwards it compares sha1
sums across the connection.

REAL-SVC: the shared key-only `sshd_node`. Real sftp, real `915` underneath,
real checksums. Nothing is stubbed, so these tests also exercise `915`'s
named-option interface as a caller actually uses it.

`906` is the layer `917`, `925`, `930` and `931` all delegate their transfers
to, which is why its guards matter more than its happy path: a silent failure
here becomes a backup that was never taken.
"""

from __future__ import annotations

import pytest

from conftest import SSH_KEY, SSH_REMOTE_USER

SCRIPT = "related-available/906_ssh-copy-to-remote-machine.sh"
REMOTE_DIR = f"/home/{SSH_REMOTE_USER}/incoming"
LOCAL = "/tmp/906/payload.gz"

pytestmark = pytest.mark.slow


@pytest.fixture
def copy(syscheck, sshd_node):
    syscheck.set_script_config(
        "906",
        "# generated by test_906_ssh_copy_to_remote_machine.py\n"
        'SSHTIMEOUT="-o ConnectTimeout=10 -o StrictHostKeyChecking=no '
        '-o UserKnownHostsFile=/dev/null -o LogLevel=ERROR"\n')
    syscheck.set_script_config(
        "915",
        "# generated by test_906_ssh_copy_to_remote_machine.py\n"
        'SSHOPTIONS="-o ConnectTimeout=10 -o StrictHostKeyChecking=no '
        '-o UserKnownHostsFile=/dev/null -o LogLevel=ERROR"\n')
    syscheck.exec(f"rm -rf /tmp/906 && mkdir -p /tmp/906 && "
                  f"head -c 2048 /dev/urandom > {LOCAL}").check()

    def remote(command: str):
        return syscheck.exec([
            "ssh", "-o", "StrictHostKeyChecking=no",
            "-o", "UserKnownHostsFile=/dev/null", "-o", "LogLevel=ERROR",
            "-i", SSH_KEY, "-l", SSH_REMOTE_USER, sshd_node, command])

    remote(f"rm -rf {REMOTE_DIR} && mkdir -p {REMOTE_DIR}").check()
    syscheck.remote = remote
    syscheck.sshd = sshd_node
    return syscheck


def args(sc, *, file: str = LOCAL, host: str | None = None,
         directory: str = REMOTE_DIR) -> tuple[str, ...]:
    return (f"--file={file}", f"--host={host or sc.sshd}",
            f"--dir={directory}", f"--user={SSH_REMOTE_USER}",
            f"--key={SSH_KEY}")


def own(run) -> list:
    return [m for m in run.messages if m.scriptid == "906"]


# --- the transfer -----------------------------------------------------------

def test_a_file_is_copied_to_the_remote_host(copy):
    copy.run_script(SCRIPT, *args(copy))

    res = copy.remote(f"ls -1 {REMOTE_DIR}")
    assert "payload.gz" in res.stdout, res.output


def test_the_copy_is_byte_identical(copy):
    """`906` verifies with sha1 across the connection; this checks the same
    thing independently, so a broken verification cannot hide a broken copy."""
    copy.run_script(SCRIPT, *args(copy))

    local = copy.exec(f"sha1sum {LOCAL}").check().stdout.split()[0]
    remote = copy.remote(f"sha1sum {REMOTE_DIR}/payload.gz").check().stdout.split()[0]
    assert local == remote, f"{local} != {remote}"


def test_a_successful_transfer_is_reported(copy):
    run = copy.run_script(SCRIPT, *args(copy))

    assert any(m.errno == "9061" and m.level == "I" for m in own(run)), run.describe()


def test_the_remote_keeps_the_original_filename(copy):
    """`906` treats `--dir` as a directory and preserves the basename — the
    contract `917` disagrees with, since it passes a full remote file path."""
    copy.run_script(SCRIPT, *args(copy))

    res = copy.remote(f"ls -1 {REMOTE_DIR}")
    assert res.stdout.strip() == "payload.gz", res.output


# --- guards before sending --------------------------------------------------

def test_an_existing_remote_file_is_refused(copy):
    """Overwriting a backup that is already there would destroy it, so `906`
    asks first and refuses."""
    copy.run_script(SCRIPT, *args(copy))

    run = copy.run_script(SCRIPT, *args(copy))

    assert any(m.errno == "9067" for m in own(run)), run.describe()


def test_a_refused_overwrite_leaves_the_remote_copy_untouched(copy):
    copy.run_script(SCRIPT, *args(copy))
    before = copy.remote(f"sha1sum {REMOTE_DIR}/payload.gz").check().stdout.split()[0]

    copy.exec(f"head -c 4096 /dev/urandom > {LOCAL}").check()
    copy.run_script(SCRIPT, *args(copy))

    after = copy.remote(f"sha1sum {REMOTE_DIR}/payload.gz").check().stdout.split()[0]
    assert before == after, "the remote file was overwritten"


def test_a_missing_local_file_is_reported(copy):
    run = copy.run_script(SCRIPT, *args(copy, file="/tmp/906/no-such-file"))

    assert own(run)[0].errno == "9062", run.describe()


def test_an_unreadable_local_file_never_reports_success(copy):
    """`906` guards with `[ ! -f "$SSHFILE" ] || [ ! -r "$SSHFILE" ]`, added as
    part of item #8 in BUGFIXES_AND_IMPROVEMENTS.

    The `-r` half of it cannot fire in practice: syscheck runs as **root**, and
    root satisfies `-r` on a mode-000 file. So a file the script "cannot read"
    is read anyway, and what actually stops the transfer is the sha1 comparison
    at the far end failing — `9066`, a hash mismatch, rather than `9062`, a bad
    input file.

    Recorded as characterisation, not a defect: the guard is still correct for
    the `-f` case and for any non-root caller, and the run does fail rather than
    claiming success, which is what matters. But it means the error an operator
    sees names the wrong thing, and no amount of local permission fixing will
    ever produce `9062` on a root install."""
    copy.exec(f"chmod 000 {LOCAL}").check()
    try:
        run = copy.run_script(SCRIPT, *args(copy))

        assert own(run), run.describe()
        assert not any(m.errno == "9061" for m in own(run)), run.describe()
    finally:
        copy.exec(f"chmod 644 {LOCAL}")


def test_a_missing_host_is_reported(copy):
    run = copy.run_script(SCRIPT, f"--file={LOCAL}", f"--dir={REMOTE_DIR}",
                          f"--user={SSH_REMOTE_USER}", f"--key={SSH_KEY}")

    assert own(run)[0].errno == "9063", run.describe()


def test_an_unreachable_host_is_reported_and_nothing_is_claimed(copy):
    run = copy.run_script(SCRIPT, *args(copy, host="no-such-host"))

    assert own(run), run.describe()
    assert not any(m.errno == "9061" for m in own(run)), run.describe()


def test_a_missing_remote_directory_is_reported(copy):
    """The disk-space probe runs `df` on the target directory; if that is not
    there the figure comes back empty, which item #8 made an explicit error
    rather than a silent comparison against nothing."""
    run = copy.run_script(SCRIPT, *args(copy, directory="/no/such/remote/dir"))

    assert own(run), run.describe()
    assert not any(m.errno == "9061" for m in own(run)), run.describe()


# --- verification after sending ---------------------------------------------

def test_the_transfer_is_verified_by_hash(copy):
    """The sha1 comparison is what makes `906` safe to build backups on. Proven
    by checking the remote really holds what the local side hashed — a transfer
    reported OK whose contents differed would be the worst outcome here."""
    run = copy.run_script(SCRIPT, *args(copy))

    assert any(m.errno == "9061" for m in own(run)), run.describe()
    local = copy.exec(f"sha1sum {LOCAL}").check().stdout.split()[0]
    remote = copy.remote(f"sha1sum {REMOTE_DIR}/payload.gz").check().stdout.split()[0]
    assert local == remote


def test_an_empty_file_transfers(copy):
    """A zero-byte file is a legitimate edge: `du --block-size=M` reports 0M for
    it, and the space check must not read that as "no figure returned"."""
    copy.exec("rm -f /tmp/906/empty.gz && touch /tmp/906/empty.gz").check()

    run = copy.run_script(SCRIPT, *args(copy, file="/tmp/906/empty.gz"))

    assert any(m.errno == "9061" for m in own(run)), run.describe()
    assert "empty.gz" in copy.remote(f"ls -1 {REMOTE_DIR}").stdout


def test_help_documents_every_error_code(copy):
    res = copy.exec([copy.script_path(SCRIPT), "--help"])

    for n in range(1, 8):
        assert f"906{n} / " in res.output, res.output

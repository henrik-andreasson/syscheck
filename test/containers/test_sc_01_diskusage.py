def test_help_documents_every_error_code(syscheck):
    res = syscheck.exec([syscheck.script_path(SCRIPT), "--help"])
    out = res.output

    assert "Scriptid: 01 - Disk usage" in out
    for errno in ("011", "012", "013"):
        assert f"{errno} / " in out, out


def test_help_does_not_emit_a_log_message(syscheck):
    """--help must not pollute last_status / syslog with a fake check result."""
    syscheck.exec([syscheck.script_path(SCRIPT), "--help"])
    assert "01-" not in syscheck.file_log()



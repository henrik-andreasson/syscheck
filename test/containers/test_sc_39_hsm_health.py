def test_a_missing_lunacm_is_reported_on_every_check(hsm):
    """Without the tool nothing can be known, and each check says so rather than
    reporting a healthy HSM."""
    hsm.set_script_config("39", config(lunacm="/usr/safenet/lunaclient/bin/lunacm"))


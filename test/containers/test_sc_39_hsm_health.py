# --- the reconstructed command, and what it hides ---------------------------

def test_the_session_guard_accepts_the_real_slot_set_line(hsm):
    """`slot set` answers, verbatim from the capture:

        Current Slot Id: 1 (Luna User Slot 7.0.1 (PW) Signing With Cloning Mode)

    `extract_colon_field ... "Current Slot Id"` returns the whole tail,
    parenthetical included, and the guard compares it with

        [[ ${APP_CURRENT_SLOT} != ${LUNA_APPLICATION_SLOT} ]]

    against a bare slot number. That can never match, so both sessions fail with
    "LunaCM did not select application partition slot" and every check reports
    the session error instead of the HSM's real state.

    Every other test in this file only passes because the fixture has `slot
    list` emit a second, bare `Current Slot Id:` line — the extractor keeps the
    **last** match, so that one wins. `slot list` output is **not** in the
    capture, so whether a real Luna emits it is unknown.

    Driven here with `slot list` silent, leaving only the real `slot set`
    answer. If a real `slot list` does emit a bare line the script is fine and
    this test should be deleted; if it does not, this is a defect that stops
    `sc_39` working at all. One capture of `lunacm slot list` settles it."""
    set_fixtures(hsm, slot_list="Command Result : No Error\n")

    run = hsm.run_script(SCRIPT)

    assert all(m.level == "I" for m in run.messages), run.describe()


def test_help_documents_every_error_code(hsm):
    res = hsm.exec([hsm.script_path(SCRIPT), "--help"])

    for n in range(1, 18):
        assert f"39{n} / " in res.output, res.output

"""End-to-end tests for scripts-available/sc_39_hsm_health.sh.

`sc_39` drives two non-interactive `lunacm` sessions against a SafeNet Luna HSM
and grades the combined output. `lunacm` is faked as a binary that reads the
piped command list on **stdin** and answers each command from a fixture.

Fixtures come from [`sc_39_luna7_sample_output.txt`](sc_39_luna7_sample_output.txt),
a real Luna 7 capture taken from the Thales LunaCM Command Reference. Field
names, value formats and the `Command Result : No Error` trailer are all
genuine, which matters here because the script's parsing is unusually literal:
it extracts by field name (`Battery Voltage`, `Partition Status`), requires unit
suffixes it strips itself (`3.093 V`, `64 deg. C`), and counts successful
command results.

**Two commands are not in the capture** and are reconstructed:

* `slot list` — needed because the session guard compares `Current Slot Id`
  against the configured slot, and the real `slot set` line carries a
  parenthetical that breaks that comparison. See
  `test_the_session_guard_accepts_the_real_slot_set_line` (D70): the default
  fixture has `slot list` emit a bare `Current Slot Id:` line, which is the only
  assumption under which the check works at all.
* `hsm envshow` — the capture has `hsm showinfo`, whose `Environmental:` block
  carries the same field names, so that block is used verbatim.
"""

from __future__ import annotations

import pytest

SCRIPT = "sc_39_hsm_health.sh"
TOOL = "/usr/local/bin/lunacm"
CALL_LOG = "/tmp/lunacm-calls.log"
FIXTURE_DIR = "/tmp/lunacm-fixtures"

APP_SLOT = 3
ADMIN_SLOT = 4

pytestmark = pytest.mark.slow

# From the capture: `role show -name co` on an activated Crypto Officer.
ROLE_ACTIVATED = """State of role 'Crypto Officer':
Activated.
Command Result : No Error
"""

ROLE_NOT_INITIALIZED = """State of role 'Crypto Officer':
Not initialized.
Command Result : No Error
"""

# From the capture, `partition showinfo` (v1).
PARTITION_OK = """Partition Label -> myPCIePar
Partition Manufacturer -> SafeNet
Partition Model -> Luna K7
Partition Serial Number -> 157956935657
Partition Status -> L3 Device
HSM Part Number -> 808-000048-002
Slot Id -> 6
Session State -> CKS_RW_PUBLIC_SESSION
Role Status -> none logged in
Partition Storage:
Total Storage Space: 6627739
Used Storage Space: 84480
Free Storage Space: 6543259
Object Count: 256
Command Result : No Error
"""

# The `Environmental:` block of `hsm showinfo` from the capture.
ENVSHOW_OK = """Environmental:
Fan 1 Status : active
Fan 2 Status : active
Battery Voltage : 3.093 V
Battery Warning Threshold Voltage : 2.750 V
System Temp : 64 deg. C
System Temperature Warning Threshold : 75 deg. C
Command Result : No Error
"""

FAKE_LUNACM = f"""#!/bin/bash
IN=$(cat)
echo "$IN" >> {CALL_LOG}
while IFS= read -r cmd ; do
  case "$cmd" in
    "slot set"*)
        slot="${{cmd##*-slot }}"
        if [ -f "{FIXTURE_DIR}/slot_set" ] ; then
          sed "s/@SLOT@/$slot/g" "{FIXTURE_DIR}/slot_set"
        fi
        ;;
    "slot list")
        if [ -f "{FIXTURE_DIR}/slot_list" ] ; then
          sed "s/@SLOT@/$slot/g" "{FIXTURE_DIR}/slot_list"
        fi
        ;;
    "role show"*)        cat "{FIXTURE_DIR}/role_show" 2>/dev/null ;;
    "partition showinfo") cat "{FIXTURE_DIR}/partition" 2>/dev/null ;;
    "hsm envshow")       cat "{FIXTURE_DIR}/envshow" 2>/dev/null ;;
    exit) : ;;
  esac
done <<< "$IN"
exit ${{LUNACM_EXIT:-0}}
"""

# The real `slot set` answer from the capture, with its parenthetical.
SLOT_SET_REAL = ("Current Slot Id: @SLOT@ "
                 "(Luna User Slot 7.0.1 (PW) Signing With Cloning Mode)\n"
                 "Command Result : No Error\n")

# Reconstructed: a bare `Current Slot Id:` from `slot list`. The extractor keeps
# the last match, so this is what makes the session guard pass. See D70.
SLOT_LIST_BARE = "Current Slot Id: @SLOT@\nCommand Result : No Error\n"


def config(*, app_slot=APP_SLOT, admin_slot=ADMIN_SLOT, timeout=10,
           battery_margin="0.100", temp_margin="5",
           storage_warn="15", storage_err="5", lunacm: str = TOOL) -> str:
    return (
        "# generated by test_sc_39_hsm_health.py\n"
        f"LUNACM={lunacm}\n"
        f"LUNA_APPLICATION_SLOT={app_slot}\n"
        f"LUNA_ADMIN_SLOT={admin_slot}\n"
        f"LUNACM_TIMEOUT={timeout}\n"
        f"BATTERY_WARNING_MARGIN_V={battery_margin}\n"
        f"TEMPERATURE_WARNING_MARGIN_C={temp_margin}\n"
        f"STORAGE_WARNING_FREE_PERCENT={storage_warn}\n"
        f"STORAGE_ERROR_FREE_PERCENT={storage_err}\n"
    )


def set_fixtures(sc, *, slot_set=SLOT_SET_REAL, slot_list=SLOT_LIST_BARE,
                 role_show=ROLE_ACTIVATED, partition=PARTITION_OK,
                 envshow=ENVSHOW_OK) -> None:
    for name, body in (("slot_set", slot_set), ("slot_list", slot_list),
                       ("role_show", role_show), ("partition", partition),
                       ("envshow", envshow)):
        sc.write_file(f"{FIXTURE_DIR}/{name}", body)


@pytest.fixture
def hsm(syscheck):
    syscheck.exec(f"rm -f {CALL_LOG} ; mkdir -p {FIXTURE_DIR}")
    syscheck.install_fake_bin("lunacm", FAKE_LUNACM)
    set_fixtures(syscheck)
    syscheck.set_script_config("39", config())
    return syscheck


def summary(run):
    return run.messages[-1]


def by_errno(run, *errnos):
    return [m for m in run.messages if m.errno in errnos]


# --- a healthy HSM ----------------------------------------------------------

def test_a_healthy_hsm_reports_every_check_ok(hsm):
    """Six checks — CO activation, partition status, two fans, battery,
    temperature, storage — then the summary."""
    run = hsm.run_script(SCRIPT)

    assert all(m.level == "I" for m in run.messages), run.describe()
    assert (summary(run).level, summary(run).errno) == ("I", "3916"), run.describe()


def test_the_summary_has_its_own_index(hsm):
    """`sc_39` resets `SCRIPTINDEX` to `00` before the summary, which is what
    `sc_08` failed to do as D50."""
    run = hsm.run_script(SCRIPT)

    assert summary(run).index == "00", run.describe()
    assert all(m.index != "00" for m in run.messages[:-1]), run.describe()


def test_both_sessions_are_driven_with_the_configured_slots(hsm):
    """The application partition and the HSM administrative partition are
    different slots, and the commands differ between them."""
    hsm.run_script(SCRIPT)

    log = hsm.read_file(CALL_LOG)
    assert f"slot set -slot {APP_SLOT}" in log, log
    assert f"slot set -slot {ADMIN_SLOT}" in log, log
    assert "role show -name co" in log, log
    assert "partition showinfo" in log, log
    assert "hsm envshow" in log, log



def test_the_summary_has_an_index_of_its_own(crl):
    """`send_mess_to_monitoring` keys the passive check by
    `${SCRIPTID}-${SCRIPTINDEX}`, so the summary needs an index the per-CRL
    verdicts never use. Before the D50 fix it ran after the loop without
    resetting `SCRIPTINDEX` and inherited the last CRL's — with one CRL
    configured both were `08-01`, pushed to the same service, the summary
    arriving second and winning. `sc_10` always did this correctly."""
    run = crl.run_script(SCRIPT)

    assert summary(run).index != per_crl(run)[-1].index, run.describe()


def test_an_empty_crl_list_is_reported_rather_than_summarised_as_ok(crl):
    """No `CRLS[]` entries at all: the loop body never runs. It used to end on an
    INFO summary, so an install that lost its CRL config looked identical to one
    where every CRL was fresh — "green means checked" quietly broken.

    It now reports `ERRNO[5]`, the script's existing "Configuration error" code,
    and the summary is an error. Deliberate behaviour change, matching the guard
    added to `sc_10` at the same time: a check that is enabled but unconfigured
    alerts rather than staying green."""
    crl.set_script_config("08", "TIMEOUT=5\nRETRIES=1\nCHECKTOOL=curl\n")

    run = crl.run_script(SCRIPT)

    assert "085" in run.errnos, run.describe()
    assert summary(run).level == "E", run.describe()


# --- multiple CRLs and the host rewrite -------------------------------------

def test_every_configured_crl_is_checked_in_order(crl):
    crl.set_script_config("08", conf(crl,
                                       (CRL_PATH, 10, 5, None),
                                     (CRL_PATH, 120, 30, None),
                                     (CRL_PATH, 120, 90, None)))

    run = crl.run_script(SCRIPT)

    assert [m.level for m in per_crl(run)] == ["I", "W", "E"], run.describe()
    assert [m.index for m in per_crl(run)] == ["01", "02", "03"], run.describe()


def test_the_host_ip_override_redirects_the_request(crl):
    """`CRL_HOST_IP` exists so a CRL published on a name that does not resolve
    from the monitoring host can still be fetched, by connecting to an address
    and passing the name in a `Host:` header. Proved by pointing the URL at a
    hostname that does not resolve and the override at the live server."""
    crl.set_script_config("08", config("crl.example.com",
                                       (CRL_PATH, 10, 5, crl.crl_server.name)))

    run = crl.run_script(SCRIPT)

    assert per_crl(run)[0].errno == "082", run.describe()


def test_a_crl_with_no_host_override_can_be_fetched(crl):
    """The host override is optional — the obvious config is a bare list of CRL
    URLs, with no `CRL_HOST_IP` at all.

    Before the D52 fix the fetch was built as
    `curl ... ${CHECK_HOST_ARG1} "${CHECK_HOST_ARG2}" ...` with the second
    **quoted**, so with no override it survived as a literal empty argument and
    curl aborted with `option : blank argument where content is expected`
    before making any request — every CRL reported undownloadable. The shipped
    config only escaped it by accident, via D51's leak from the first entry.

    An array expands to nothing when empty, so the bare-URL config now works."""
    crl.set_script_config("08", config(crl.crl_server.name,
                                       (CRL_PATH, 10, 5, None)))

    run = crl.run_script(SCRIPT)

    assert per_crl(run)[0].errno == "082", run.describe()


def test_thresholds_do_not_leak_from_one_crl_to_the_next(crl):
    """`checkcrl` sets `ARGWARNMIN`/`ARGERRMIN` only when the entry configures a
    threshold. They used to be plain globals with no reset on the "default"
    path, so an entry that omits `MINUTES` silently ran with the previous
    entry's value — and the same leak carried an earlier CRL's `Host:` header
    to a later one, which is how a check ends up validating the wrong file.

    Here the first CRL sets a 120-minute warn floor and the second sets none;
    the second must fall back to half its own lifetime and be OK. `local`
    declarations make each call start clean."""
    crl.set_script_config("08", conf(crl,
                                       (CRL_PATH, 120, 30, None),
                                       (CRL_PATH, None, None, None)))

    run = crl.run_script(SCRIPT)

    assert [m.level for m in per_crl(run)] == ["W", "I"], run.describe()


def test_the_temporary_file_is_removed_on_every_exit_path(crl):
    """`checkcrl` creates its download target with `mktemp` and used to remove it
    only on the success path, so each of the five early `return`s leaked a file
    into /tmp — and a CRL that cannot be fetched hits one of them every run.

    A `RETURN` trap now covers all of them. `EXIT` would not: bash traps are
    global, and `checkcrl` is called once per configured CRL, so an `EXIT` trap
    would only clean up after the last one."""
    before = crl.exec("ls -1 /tmp/tmp.* 2>/dev/null | wc -l").check().stdout.strip()

    crl.set_script_config("08", conf(crl,
                                     ("/no-such.crl", 10, 5, None),
                                     (CRL_PATH, 10, 5, None),
                                     ("/also-missing.crl", 10, 5, None)))
    crl.run_script(SCRIPT)

    after = crl.exec("ls -1 /tmp/tmp.* 2>/dev/null | wc -l").check().stdout.strip()
    assert after == before, f"leaked {int(after) - int(before)} temp files"


def test_help_documents_every_error_code(crl):
    res = crl.exec([crl.script_path(SCRIPT), "--help"])

    for n in range(1, 10):
        assert f"08{n} / " in res.output, res.output

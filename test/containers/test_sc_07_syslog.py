"""End-to-end tests for scripts-available/sc_07_syslog.sh.

This one needs no mock at all: the test image runs a real `rsyslogd` writing to
`/var/log/syslog`, so the script's round trip — `logger` a unique marker, wait,
look for it in the log file — is exercised against a real syslog daemon end to
end. That makes it the highest-fidelity check in Phase 1, and the failure paths
are produced by breaking the real setup rather than by faking its output:

* daemon down       — point the check at a process name that is not running
* message lost      — point `localsyslogfile` at a file syslog does not write to

`WAIT_TIME` is shortened from the shipped 5s; the round trip through a local
`imuxsock` is immediate, and every test here pays it.
"""

from __future__ import annotations

import pytest

SCRIPT = "sc_07_syslog.sh"
SYSLOG_FILE = "/var/log/syslog"


def config(procname: str = "rsyslogd", pidfile: str = "/var/run/syslogd.pid",
           logfile: str = SYSLOG_FILE, wait: int = 2) -> str:
    return (
        "# generated by test_sc_07_syslog.py\n"
        f"WAIT_TIME={wait}\n"
        f"localsyslogfile={logfile}\n"
        f"pidfile={pidfile}\n"
        f"procname={procname}\n"
    )


@pytest.fixture
def syslog(syscheck):
    syscheck.set_script_config("07", config())
    # the daemon is started once with the container; a previous test must not be
    # able to leave it stopped
    syscheck.exec("pgrep rsyslogd >/dev/null || rsyslogd")
    syscheck.exec("for i in 1 2 3 4 5 ; do [ -S /dev/log ] && break ; sleep 0.2 ; done")
    return syscheck


def test_a_delivered_message_is_reported_ok(syslog):
    """The whole point of the check: syslog is up *and* messages arrive."""
    run = syslog.run_script(SCRIPT)

    msg = run.only()
    assert (msg.level, msg.errno) == ("I", "073"), run.describe()


def test_the_marker_really_reaches_the_log_file(syslog):
    """Asserts the round trip from the other side — the script's own INFO would
    look identical if it never logged anything and grepped a log full of its own
    output."""
    before = syslog.syslog()

    syslog.run_script(SCRIPT)

    added = syslog.syslog()[len(before):]
    assert "syscheck test message:" in added, added[-2000:]


def test_a_stopped_syslog_daemon_is_reported_as_an_error(syslog):
    """`procname` names a daemon that is not running — what a host whose syslog
    died, or which runs syslog-ng under a different name than the config
    expects, looks like to this check."""
    syslog.set_script_config("07", config(procname="no-such-syslogd",
                                          pidfile="/no/such/syslogd.pid"))

    run = syslog.run_script(SCRIPT)

    msg = run.only()
    assert (msg.level, msg.errno) == ("E", "072"), run.describe()
    assert run.exit_code == 2, run.describe()


def test_a_stopped_daemon_stops_the_check_before_the_round_trip(syslog):
    """No point logging a marker to a daemon that is down, and reporting both
    failures would double-alert on one fault."""
    syslog.set_script_config("07", config(procname="no-such-syslogd",
                                          pidfile="/no/such/syslogd.pid"))

    run = syslog.run_script(SCRIPT)

    assert len(run.messages) == 1, run.describe()


def test_a_message_that_does_not_arrive_is_reported_as_an_error(syslog):
    """The daemon is alive but the message never lands in the file the operator
    reads — a misrouted facility, a full disk, or a `localsyslogfile` pointing
    at the wrong path. The shipped config points at `/var/log/messages`, which
    is not where a default Debian rsyslog writes, so this is the path a fresh
    install most likely takes."""
    syslog.exec("rm -f /tmp/nothing-writes-here && touch /tmp/nothing-writes-here")
    syslog.set_script_config("07", config(logfile="/tmp/nothing-writes-here"))

    run = syslog.run_script(SCRIPT)

    msg = run.only()
    assert (msg.level, msg.errno) == ("E", "071"), run.describe()
    assert run.exit_code == 1, run.describe()


def test_a_missing_log_file_is_reported_as_an_error(syslog):
    """`tail` on a path that does not exist must not read as a healthy check."""
    syslog.set_script_config("07", config(logfile="/no/such/messages"))

    run = syslog.run_script(SCRIPT)

    assert run.only().errno == "071", run.describe()


def test_each_run_looks_for_its_own_marker(syslog):
    """The marker is `${RANDOM}_$$`, so a previous run's message sitting in the
    log cannot satisfy this one — otherwise the check would keep passing for as
    long as the log retains one old marker, however dead syslog is now."""
    first = syslog.run_script(SCRIPT)
    assert first.only().errno == "073", first.describe()

    markers = [line for line in syslog.syslog().splitlines()
               if "syscheck test message:" in line]
    assert len(markers) == 1, markers

    # the log still holds the first marker; with syslog now unable to deliver,
    # the check must fail rather than match what is already there
    syslog.exec(f"cp {SYSLOG_FILE} /tmp/frozen-syslog")
    syslog.set_script_config("07", config(logfile="/tmp/frozen-syslog"))

    second = syslog.run_script(SCRIPT)
    assert second.only().errno == "071", second.describe()


def test_help_documents_every_error_code(syslog):
    res = syslog.exec([syslog.script_path(SCRIPT), "--help"])

    for errno in ("071", "072", "073"):
        assert f"{errno} / " in res.output, res.output


def test_the_daemon_down_message_carries_a_real_index(syslog):
    """The regression guard for D29. `initscript` leaves `SCRIPTINDEX=00` and
    sc_07 used to call `addOneToIndex` only *after* the process check, so the
    "syslog is not running" message went out with index 00 while the round-trip
    messages used 01 — one fault arriving under a service name nothing else ever
    produces, on the check whose job is to notice that logging stopped. All
    three of this script's messages are outcomes of one check, so they share
    index 01."""
    syslog.set_script_config("07", config(procname="no-such-syslogd",
                                          pidfile="/no/such/syslogd.pid"))

    run = syslog.run_script(SCRIPT)

    assert run.only().index == "01", run.describe()

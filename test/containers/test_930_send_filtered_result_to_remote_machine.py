"""End-to-end tests for related-available/930_send_filtered_result_to_remote_machine.sh.

`930` ships syscheck's filtered status file to one or more monitoring hosts. It
owns no transport of its own — every send is delegated to `906`, so this is a
composition test: the thing worth proving is that it hands `906` the right
arguments and reports what comes back.

REAL-SVC: the shared key-only `sshd_node`, the real `906` and the real `915`
beneath it. The only thing arranged here is the symlink into
`related-enabled/`, which `930` looks through and which an install creates —
`enable_906_ssh_copy_to_remote_machine` defaults to `true` in the ansible role.

`930` used to reach `906` through `related-enabled/`, requiring it to have been
*enabled* rather than merely installed. That path moved to `related-available/`
on 2026-09-18, as `905`, `919`, `925` and `931` did.
"""

from __future__ import annotations

import pytest

from conftest import SSH_KEY, SSH_REMOTE_USER

SCRIPT = "related-available/930_send_filtered_result_to_remote_machine.sh"
HELPER_SRC = "related-available/906_ssh-copy-to-remote-machine.sh"
HELPER_LINK = "related-available/906_ssh-copy-to-remote-machine.sh"
LOCAL = "/tmp/930/last_status_filtered"
REMOTE_DIR = f"/home/{SSH_REMOTE_USER}/monitoring"

pytestmark = pytest.mark.slow

SSH_OPTS = ('"-o ConnectTimeout=10 -o StrictHostKeyChecking=no '
            '-o UserKnownHostsFile=/dev/null -o LogLevel=ERROR"')


def config(sc, *, hosts=None, local: str = LOCAL, directory: str = REMOTE_DIR) -> str:
    hosts = hosts or [sc.sshd]
    lines = ["# generated by test_930_send_filtered_result_to_remote_machine.py\n"]
    for i, host in enumerate(hosts):
        lines.append(f'REMOTE_HOSTNAME[{i}]="{host}"\n')
        lines.append(f'LOCAL_FILE[{i}]="{local}"\n')
        lines.append(f"REMOTE_DIR[{i}]='{directory}'\n")
        lines.append(f"REMOTE_USER[{i}]='{SSH_REMOTE_USER}'\n")
        lines.append(f"SSHKEY[{i}]='{SSH_KEY}'\n")
    return "".join(lines)


@pytest.fixture
def sender(syscheck, sshd_node):
    syscheck.sshd = sshd_node
    # an install symlinks enabled helpers here; 930 looks through related-enabled
    # 930 reaches 906 through related-available/ since 2026-09-18, which is the
    # real script; nothing to link, and reset() restores the tree per test
    for scriptid in ("906", "915"):
        syscheck.set_script_config(
            scriptid,
            f"# generated by test_930\n"
            f'{"SSHTIMEOUT" if scriptid == "906" else "SSHOPTIONS"}={SSH_OPTS}\n')
    syscheck.exec(f"rm -rf /tmp/930 && mkdir -p /tmp/930 && "
                  f"printf 'status line\\n' > {LOCAL}").check()

    def remote(command: str):
        return syscheck.exec([
            "ssh", "-o", "StrictHostKeyChecking=no",
            "-o", "UserKnownHostsFile=/dev/null", "-o", "LogLevel=ERROR",
            "-i", SSH_KEY, "-l", SSH_REMOTE_USER, sshd_node, command])

    remote(f"rm -rf {REMOTE_DIR} && mkdir -p {REMOTE_DIR}").check()
    syscheck.remote = remote
    syscheck.set_script_config("930", config(syscheck))
    return syscheck


def own(run) -> list:
    return [m for m in run.messages if m.scriptid == "930"]


# --- the delegation ---------------------------------------------------------

def test_the_status_file_reaches_the_remote_host(sender):
    sender.run_script(SCRIPT)

    res = sender.remote(f"ls -1 {REMOTE_DIR}")
    assert "last_status_filtered" in res.stdout, res.output


def test_the_remote_copy_matches_the_local_file(sender):
    sender.run_script(SCRIPT)

    res = sender.remote(f"cat {REMOTE_DIR}/last_status_filtered")
    assert "status line" in res.stdout, res.output


def test_a_successful_transfer_is_reported(sender):
    run = sender.run_script(SCRIPT)

    assert any(m.errno == "9301" and m.level == "I" for m in own(run)), run.describe()


def test_every_configured_host_gets_the_file(sender):
    """Two entries pointing at the same server, which is all `930` can tell
    apart — it reports per entry, not per host."""
    sender.set_script_config("930", config(sender, hosts=[sender.sshd, sender.sshd]))

    run = sender.run_script(SCRIPT)

    assert len(own(run)) == 2, run.describe()


def test_each_entry_reports_under_its_own_index(sender):
    """`930` does call `addOneToIndex`, unlike `916`, so each
    destination is its own monitoring service."""
    sender.set_script_config("930", config(sender, hosts=[sender.sshd, sender.sshd]))

    run = sender.run_script(SCRIPT)

    indexes = [m.index for m in own(run)]
    assert len(set(indexes)) == len(indexes), run.describe()


# --- failures ---------------------------------------------------------------

def test_an_unreachable_host_is_reported_as_a_failure(sender):
    sender.set_script_config("930", config(sender, hosts=["no-such-host"]))

    run = sender.run_script(SCRIPT)

    msg = own(run)[0]
    assert (msg.level, msg.errno) == ("E", "9302"), run.describe()


def test_a_missing_local_file_is_reported_as_a_failure(sender):
    """`930` does not check the file itself; it relies on `906` refusing. The
    refusal has to surface as `930`'s own error rather than being swallowed."""
    sender.set_script_config("930", config(sender, local="/tmp/930/no-such-file"))

    run = sender.run_script(SCRIPT)

    assert any(m.errno == "9302" for m in own(run)), run.describe()


def test_a_failure_carries_what_906_said(sender):
    """D116, fixed 2026-09-18. `930` captured `906`'s output into `SSHCOPYRES`
    and built a detailed string naming the host, directory, user, key and result
    — then passed it as `-3`, which `DESCR[2]`'s two placeholders could not
    render. Everything it had learned about *why* the transfer failed was
    assembled and then discarded.

    Compounded by the other half: the arguments started at `-2`, so the filename
    landed in the "result" slot and the "file" slot was blank. The message an
    operator saw was `Could not transfer file: result:/tmp/930/...`.

    `DESCR[2]` now carries file, host and result. Dir, user and key were dropped
    from the detail rather than given placeholders — they are all in the config
    already, so echoing them back adds length without information, while the
    host is what distinguishes one configured destination from another."""
    sender.set_script_config("930", config(sender, hosts=["no-such-host"]))

    run = sender.run_script(SCRIPT)

    assert "no-such-host" in own(run)[0].text, own(run)[0].text
    assert "last_status_filtered" in own(run)[0].text, own(run)[0].text


def test_one_failing_destination_does_not_stop_the_others(sender):
    sender.set_script_config("930", config(sender, hosts=["no-such-host", sender.sshd]))

    run = sender.run_script(SCRIPT)

    assert [m.errno for m in own(run)] == ["9302", "9301"], run.describe()
    assert "last_status_filtered" in sender.remote(f"ls -1 {REMOTE_DIR}").stdout


# --- known defect -----------------------------------------------------------

def test_the_failure_message_names_the_file(sender):
    """`DESCR[2]` is `"Could not transfer file:%s result:%s"` — two
    placeholders. The failure branch passes

        -2 "${LOCAL_FILE[$j]}" -3 "file: ... result: ${SSHCOPYRES}"

    starting at `-2`, so `ARG1` is empty and the message reads
    `Could not transfer file: result:/tmp/930/...` — the filename lands in the
    *result* slot and the file slot is blank.

    The success branch directly above it gets this right with `-1` and `-2`.
    Same family as D77 in `917` and the `-2`-without-`-1` call fixed in `926`."""
    sender.set_script_config("930", config(sender, hosts=["no-such-host"]))

    run = sender.run_script(SCRIPT)

    assert own(run)[0].text.startswith("Could not transfer file:/tmp/930"), \
        own(run)[0].text


def test_help_documents_every_error_code(sender):
    res = sender.exec([sender.script_path(SCRIPT), "--help"])

    for errno in ("9301", "9302"):
        assert f"{errno} / " in res.output, res.output
